package com.company;

import java.util.Scanner;

public class L16_PQ44_repeat {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        System.out.println("Enter the value of n: ");
        int n = sc.nextInt();
        int i = 1;
        while(i<=n){
            System.out.println("The number is:" +n);
            i++;
        }
    }
}
